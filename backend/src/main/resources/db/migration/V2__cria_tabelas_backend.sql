CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    telefone VARCHAR(20) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    lgpd_consentimento_em TIMESTAMPTZ NOT NULL,
    suspenso BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMPTZ NOT NULL
);

CREATE TABLE demandas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    confeccao_id BIGINT NOT NULL REFERENCES users(id),
    servico VARCHAR(120) NOT NULL,
    quantidade INTEGER NOT NULL,
    prazo DATE NOT NULL,
    local_execucao VARCHAR(120) NOT NULL,
    descricao VARCHAR(1000),
    status VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL
);

CREATE TABLE propostas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    faccao_id BIGINT NOT NULL REFERENCES users(id),
    preco NUMERIC(12,2) NOT NULL,
    prazo_dias INTEGER NOT NULL,
    mensagem VARCHAR(500),
    status VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL,

    CONSTRAINT uq_propostas_demanda_faccao
        UNIQUE (demanda_id, faccao_id)
);

CREATE TABLE acordos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposta_id BIGINT NOT NULL UNIQUE REFERENCES propostas(id),
    demanda_id BIGINT NOT NULL REFERENCES demandas(id),
    confeccao_id BIGINT NOT NULL REFERENCES users(id),
    faccao_id BIGINT NOT NULL REFERENCES users(id),
    preco NUMERIC(12,2) NOT NULL,
    prazo_dias INTEGER NOT NULL,
    data_limite DATE NOT NULL,
    status VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL
);